const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const {pathToFileURL} = require('node:url');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({headless: true, channel: 'msedge'});
  const page = await browser.newPage({viewport: {width: 1280, height: 800}});
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(pathToFileURL(path.resolve('index.html')).href);
  const card = page.locator('.q-card').first();
  assert.equal(await page.locator('.q-card').count(), 54);
  // Selected tags can be removed directly, even with the tag picker collapsed.
  const tagsToSelect = ['几何', '计数'];
  const matchesTags = tags => page.evaluate(tags => Object.values(KANGAROO_DATA).flat().filter(q => q.tags.some(t => tags.includes(t))).length, tags);
  await page.click('#btnToggleTags');
  for (const tag of tagsToSelect) await page.locator('.tag-chip').filter({hasText: new RegExp('^' + tag + '\\d+$')}).click();
  assert.equal(await page.locator('.q-card').count(), await matchesTags(tagsToSelect));
  await page.click('#btnToggleTags');
  await page.getByRole('button', {name:'取消“几何”筛选', exact:true}).locator('span').click();
  assert.equal(await page.locator('.q-card').count(), await matchesTags(['计数']));
  assert.equal(await page.locator('#activeTags button').count(), 1);
  assert.equal(await page.locator('.tag-chip.active').count(), 1);
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('.q-card').count(), 54);
  assert.equal(await page.locator('#activeTags').innerText(), '未选标签');
  await page.selectOption('#yearSel', '2002');
  await page.fill('#search', '3');
  const beforeTag = await page.locator('.q-card').count();
  await page.click('#btnToggleTags');
  await page.locator('.tag-chip').filter({hasText: /^几何\d+$/}).click();
  await page.getByRole('button', {name:'取消“几何”筛选', exact:true}).click();
  assert.equal(await page.locator('.q-card').count(), beforeTag);
  assert.equal(await page.locator('#yearSel').inputValue(), '2002');
  assert.equal(await page.locator('#search').inputValue(), '3');
  await page.fill('#search', '');
  await page.selectOption('#yearSel', 'all');
  await page.click('#btnToggleTags');
  assert.equal(await page.getByRole('button', {name:'延申拓展', exact:true}).count(), 54);
  assert.equal(await page.locator('.extension').count(), 0);
  const extensionKeys = await page.evaluate(() => Object.keys(KANGAROO_EXTENSIONS));
  const questionKeys = await page.evaluate(() => Object.entries(KANGAROO_DATA).flatMap(([y, qs]) => qs.map(q => y + '-' + q.no)));
  assert.deepEqual(extensionKeys.sort(), questionKeys.sort());
  for (const key of questionKeys) {
    const [year, no] = key.split('-');
    const current = page.locator(`.q-card[data-year="${year}"][data-no="${no}"]`);
    const toggle = current.getByRole('button', {name:'延申拓展', exact:true});
    await toggle.click();
    assert.equal(await toggle.getAttribute('aria-expanded'), 'true');
    assert.equal(await current.locator('.extension details[open]').count(), 0);
    const expected = await page.evaluate(key => KANGAROO_EXTENSIONS[key], key);
    for (const field of ['text', 'change', 'method', 'answer', 'solution']) assert.ok(expected[field]?.trim(), `${key}: ${field}`);
    assert.equal(await current.locator('.extension-text').innerText(), expected.text);
    await current.locator('.extension-answer summary').click();
    assert.equal(await current.locator('.extension-answer strong').innerText(), expected.answer);
    assert.equal(await current.locator('.extension-answer p').last().innerText(), expected.solution);
    await toggle.click();
    await current.locator('.extension').waitFor({state:'detached'});
  }
  // Independently enumerate the variants where duplicate counting and bounds matter.
  const checkedAnswers = await page.evaluate(() => Object.fromEntries(['2002-4','2002-15','2002-16','2002-17','2002-23','2002-28'].map(k => [k, KANGAROO_EXTENSIONS[k].answer])));
  const digits = n => String(n).split('').map(Number);
  const validNumbers = Array.from({length:900}, (_, i) => i + 100).filter(n => {const [a,b,c] = digits(n); return b*b === 3*(a+c);});
  assert.equal(checkedAnswers['2002-4'], String(Math.max(...validNumbers)));
  let triangles = 0;
  for (let a = 1; a <= 9; a++) for (let b = a + 1; b <= 9; b++) if (a !== 2 && b !== 2 && a + 2 > b && a + b > 2) triangles++;
  assert.equal(checkedAnswers['2002-15'], `${triangles} triangles`);
  const rays = [0,20,50,90,130,180], angles = new Set();
  for (const a of rays) for (const b of rays) if (b > a && b - a < 180) angles.add(b - a);
  assert.equal(checkedAnswers['2002-16'], `${angles.size} distinct measures`);
  const multiples = Array.from({length:900}, (_, i) => i + 100).filter(n => n % 25 === 0 && digits(n).every(d => [0,3,5,7].includes(d)) && new Set(digits(n)).size === 3);
  assert.equal(checkedAnswers['2002-17'], `${multiples.length} numbers`);
  const claps = Array.from({length:100}, (_, i) => i + 1).filter(n => n % 3 === 0 || String(n).includes('3')).length;
  assert.equal(checkedAnswers['2002-23'], `${claps} claps`);
  const digitSum = n => digits(n).reduce((a,b) => a + b, 0);
  assert.equal(parseInt(checkedAnswers['2002-28']), Math.max(...Array.from({length:9000}, (_, i) => digitSum(digitSum(i + 1000)))));
  assert.equal(await page.locator('.tip').count(), 0);
  for (const label of ['备课提示', '详解', '多种思路', '答案']) {
    const button = card.getByRole('button', {name:label, exact:true});
    assert.equal(await button.getAttribute('aria-expanded'), 'false');
    await button.click();
    assert.equal(await button.getAttribute('aria-expanded'), 'true');
    if (label === '备课提示') assert.equal(await card.locator('.tip').count(), 1);
    await button.click(); await page.waitForTimeout(200);
    assert.equal(await button.getAttribute('aria-expanded'), 'false');
  }
  assert.equal(await card.locator('.tip').count(), 0);

  assert.equal(await page.locator('.hint').count(), 0);
  assert.equal(await card.getByText('编辑 Hint', {exact:true}).count(), 0);
  await card.locator('button[onclick="showHint(this)"]').click();
  assert.equal(await card.locator('.hint li').count(), 3);
  assert.equal(await card.locator('.hint button').innerText(), '编辑 Hint');
  await card.locator('button[onclick="showHint(this)"]').click();
  await page.waitForTimeout(200);
  assert.equal(await card.locator('.hint').count(), 0);
  await card.locator('button[onclick="showHint(this)"]').click();
  await card.getByText('编辑 Hint', {exact:true}).click();
  await page.locator('textarea').first().fill('自定义浅层提示 <test>');
  await page.click('#addHint');
  await page.locator('textarea').last().fill('第四条提示');
  await page.getByText('保存 Hint', {exact:true}).click();
  assert.equal(await card.locator('.hint li').count(), 4);
  assert.equal(await card.locator('.hint li').first().innerText(), '自定义浅层提示 <test>');
  await page.reload();
  assert.equal(await page.locator('.hint').count(), 0);
  await card.locator('button[onclick="showHint(this)"]').click();
  assert.equal(await card.locator('.hint li').count(), 4);
  await card.getByText('编辑 Hint', {exact:true}).click();
  await page.locator('textarea').first().fill('取消的内容');
  await page.click('#cancelHints');
  assert.equal(await card.locator('.hint li').first().innerText(), '自定义浅层提示 <test>');
  await page.click('#modeToggle');
  assert.equal(await page.locator('.hint').count(), 0);
  assert.equal(await card.locator('.q-actions button').count(), 2);
  await card.getByRole('button', {name:'延申拓展', exact:true}).click();
  await card.locator('.extension-answer summary').focus();
  await page.keyboard.press('Enter');
  assert.equal(await card.locator('.extension-answer[open]').count(), 1);
  assert.equal(await card.locator('.correct.option').count(), 0);
  assert.equal(await page.locator('.extension').count(), 1);
  await page.selectOption('#yearSel', '2002');
  assert.equal(await page.locator('.extension').count(), 0);
  await page.selectOption('#yearSel', 'all');
  assert.equal(await card.locator('.extension').count(), 1);
  assert.equal(await card.locator('.extension-answer[open]').count(), 0);
  page.once('dialog', d => d.dismiss());
  await card.locator('button[onclick="showHint(this)"]').click();
  await page.waitForTimeout(200);
  assert.equal(await card.locator('.hint').count(), 0);
  for (const n of [1,2,3,4,1]) {
    page.once('dialog', d => d.accept());
    await card.locator('button[onclick="showHint(this)"]').click();
    assert.equal(await card.locator('.hint h4').innerText(), `Hint ${n} / 4`);
  }
  assert.equal(await card.locator('.hint p').innerText(), '自定义浅层提示 <test>');
  const second = page.locator('.q-card').nth(1);
  await second.locator('[data-letter="A"]').click();
  assert.equal(await second.locator('.incorrect.option').count(), 1);
  assert.equal(await card.locator('.incorrect.option').count(), 0);
  await second.locator('[data-letter="E"]').click();
  assert.equal(await second.locator('.correct.option').count(), 1);
  await page.selectOption('#yearSel','2002');
  assert.equal(await page.locator('.q-card').count(),30);
  assert.match(await card.locator('.q-title').innerText(), /Grade 5-6/);
  await page.selectOption('#viewSel','single');
  assert.equal(await page.locator('.q-card').count(),1);
  await page.selectOption('#viewSel','list');
  await page.setViewportSize({width:390,height:844});
  await card.getByRole('button', {name:'延申拓展', exact:true}).click();
  await card.locator('.extension-answer summary').click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true);
  await page.locator('#app').hover(); await page.mouse.wheel(0,600); await page.waitForTimeout(200);
  assert.ok(await page.locator('#app').evaluate(el => el.scrollTop > 0));
  assert.equal(await page.locator('.q-card').count(),30);
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: all 54 extensions, independent math checks, keyboard disclosure, answer isolation, filters, mobile layout, existing hints and practice flows.');
})().catch(e => {console.error(e);process.exitCode=1;});
